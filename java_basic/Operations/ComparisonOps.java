package java_basic.Operations;

public class ComparisonOps {
    public static void main(String[] args) {
        int a = 100;
        int b = 10;

        System.out.println( a == b);
        System.out.println( a != b);
        System.out.println( a > b);
        System.out.println( a < b);
        System.out.println( a >= b);
        System.out.println( a <= b);
    }
}
